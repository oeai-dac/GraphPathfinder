// model.json → an SQL script for PostgreSQL + PostGIS. pg_dump of the loaded database is the real
// test input; this script only has to produce a database the way a project would set one up.
// pg-roundtrip.ps1 calls it and writes the script into its temporary folder:
//
//   node to-postgres.mjs <out.sql>
import { readFileSync, writeFileSync } from 'node:fs'

const target = process.argv[2]
if (!target) {
  console.error('Usage: node to-postgres.mjs <out.sql>   (pg-roundtrip.ps1 does this for you)')
  process.exit(2)
}

const { tables, srid } = JSON.parse(readFileSync(new URL('./model.json', import.meta.url), 'utf8'))
const q = (t) => `${t.schema ?? 'public'}.${t.name}`
const lit = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const DECIMAL = { weight_g: 'numeric(8,1)', volume_m3: 'numeric(10,2)' }
const SQL_TYPES = {
  key: () => 'character varying(40)', text: () => 'text', longtext: () => 'text', integer: () => 'integer',
  decimal: (c) => DECIMAL[c.name] ?? 'numeric(8,2)', identity: () => 'integer GENERATED BY DEFAULT AS IDENTITY',
  geometry: (c) => `public.geometry(${c.geometryType[0] + c.geometryType.slice(1).toLowerCase()}${c.hasZ ? 'Z' : ''},${srid})`,
}
const sqlType = (c) => SQL_TYPES[c.type](c)

const out = [
  '-- Serpent\'s Meadow (fictional) as a normalised excavation database. Generated by to-postgres.mjs.',
  'CREATE EXTENSION IF NOT EXISTS postgis;',
  'CREATE SCHEMA vocab;',
  "COMMENT ON SCHEMA vocab IS 'Controlled vocabularies';",
  '',
]
for (const t of tables) {
  const defs = t.columns.map(c => `    ${c.name} ${sqlType(c)}${t.primaryKey.length === 1 && t.primaryKey[0] === c.name ? ' NOT NULL' : ''}`)
  defs.push(`    CONSTRAINT ${t.name}_pkey PRIMARY KEY (${t.primaryKey.join(', ')})`)
  for (const u of t.uniques ?? []) defs.push(`    CONSTRAINT ${t.name}_${u.join('_')}_key UNIQUE (${u.join(', ')})`)
  out.push(`CREATE TABLE ${q(t)} (\n${defs.join(',\n')}\n);`)
  out.push(`COMMENT ON TABLE ${q(t)} IS ${lit(`${t.name} (fictional example data)`)};`)
  for (const c of t.columns.filter(c => c.type === 'geometry')) out.push(`CREATE INDEX ${t.name}_${c.name}_idx ON ${q(t)} USING gist (${c.name});`)
  out.push('')
}
// Foreign keys after all tables exist (vocab tables come first, the self-reference needs its table).
for (const t of tables) for (const fk of t.foreignKeys) {
  out.push(`ALTER TABLE ${q(t)} ADD CONSTRAINT ${fk.name} FOREIGN KEY (${fk.columns.join(', ')}) REFERENCES ${fk.refSchema ?? 'public'}.${fk.refTable} (${fk.refColumns.join(', ')});`)
}
out.push('')
for (const t of tables) {
  const names = t.columns.map(c => c.name)
  for (const r of t.rows) {
    const vals = t.columns.map(c => (c.type === 'geometry' && r[c.name] ? `public.ST_GeomFromText(${lit(r[c.name])}, ${srid})` : lit(r[c.name])))
    out.push(`INSERT INTO ${q(t)} (${names.join(', ')}) VALUES (${vals.join(', ')});`)
  }
  for (const c of t.columns.filter(c => c.type === 'identity')) {
    out.push(`SELECT setval(pg_get_serial_sequence('${q(t)}', '${c.name}'), (SELECT max(${c.name}) FROM ${q(t)}));`)
  }
}
writeFileSync(target, out.join('\n') + '\n')
console.log(`${target}: ${out.length} lines`)
